// Writes supabase/migrations/34_publish_terms_privacy.sql from the bundled legal
// texts in src/content/legal, so the database and the bundle publish the same
// words. Run it after editing terms.md or privacy.md:
//
//   node scripts/build-legal-migration.mjs
//
// The migration publishes each text as the next version of its doc_type, the
// way publish_legal_document() does (migration 18): the old current row is
// flipped to is_current = false and a new row is inserted with version + 1.
// Both documents stay required for every role, as version 1 was, so every
// signed-in user is asked to accept them again through ConsentGate.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => readFileSync(join(root, 'src/content/legal', name), 'utf8').replace(/\r\n/g, '\n').trimEnd();

const docs = [
  { docType: 'terms', title: 'Terms and Conditions', body: read('terms.md') },
  { docType: 'privacy', title: 'Privacy Policy', body: read('privacy.md') },
];

const TAG = '$legal_body$';
for (const d of docs) {
  if (d.body.includes(TAG)) throw new Error(`${d.docType} body contains the dollar-quote tag ${TAG}`);
}

const publish = (d) => `-- ${d.title} -----------------------------------------------------------
do $$
declare v_next int;
begin
  select coalesce(max(version), 0) + 1 into v_next
    from public.legal_documents where doc_type = '${d.docType}';
  update public.legal_documents set is_current = false
    where doc_type = '${d.docType}' and is_current;
  insert into public.legal_documents
    (doc_type, version, title, body, is_required, applies_to_roles, is_current, published_by)
  values ('${d.docType}', v_next, '${d.title}', ${TAG}${d.body}${TAG}, true, null, true, null);
end $$;
`;

const sql = `-- Publish the Terms and Conditions and the Privacy Policy.
--
-- GENERATED by scripts/build-legal-migration.mjs from src/content/legal/*.md.
-- Edit the .md files and regenerate; do not edit this file by hand.
--
-- OPTIONAL, AND NOT YET TO BE APPLIED. Apply it only when all of these are true:
--  * a legal practitioner registered in Zimbabwe has reviewed both texts, and the
--    draft notice at the top of each has been removed;
--  * every [placeholder] (company name, address, registration number, domain,
--    Data Protection Officer, POTRAZ licence number, website host) is filled in;
--  * migration 33 (account deletion) is applied and its daily purge is scheduled,
--    and the storage worker that empties account_purge_storage_queue is running,
--    because both documents promise deletion 30 days after a request.
--
-- What it does: for 'terms' and 'privacy', exactly what publish_legal_document()
-- (migration 18) does, without its super-admin check, which a migration cannot
-- pass (auth.uid() is null): the next version number is max(version) + 1, the
-- current row is set is_current = false, and the new row is inserted current,
-- required, for all roles (applies_to_roles null, as in version 1), with
-- published_by null and effective_at / published_at defaulting to now(). The
-- unique index legal_documents_one_current holds because the old row is flipped
-- first, in the same block.
--
-- Effect: outstanding_consents() now lists both documents for every signed-in
-- user, so ConsentGate asks everyone to accept them on their next visit, and
-- record_consent() accepts only the new versions. The audit_legal_documents
-- trigger records both publishes.

${docs.map(publish).join('\n')}`;

writeFileSync(join(root, 'supabase/migrations/34_publish_terms_privacy.sql'), sql);
console.log('Wrote supabase/migrations/34_publish_terms_privacy.sql');
